"""End-to-end training for unified DELTA-ZSC.

All training data are generated by the base policy.  This keeps PPO exactly
on-policy and makes the privileged decision emission a local one-action
improvement model around the same continuation policy.  The latent estimator
cannot change data collection during training; deployment adaptation is the
analytic KL-constrained solution applied after estimation.
"""

